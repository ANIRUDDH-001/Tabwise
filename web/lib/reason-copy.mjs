export function reasonText(code){
 if(typeof code!=='string'||!code)return 'Something went wrong. Try again.';
 if(Object.hasOwn(REASON_COPY,code))return REASON_COPY[code];
 return /^[a-z0-9_]{1,80}$/.test(code)?`Something went wrong (code: ${code}).`:'Something went wrong. Try again.';
}
